import puppeteer, { type Browser } from "puppeteer";
import type { ToolCallResult } from "./toolRegistry";

let browser: Browser | null = null;

async function getBrowser(): Promise<Browser> {
  if (browser) {
    try {
      await browser.version();
      return browser;
    } catch {
      browser = null;
    }
  }
  browser = await puppeteer.launch({
    headless: true,
    args: ["--no-sandbox", "--disable-setuid-sandbox", "--disable-dev-shm-usage", "--disable-gpu"],
    executablePath: process.env.PUPPETEER_EXECUTABLE_PATH || undefined,
  });
  return browser;
}

function esc(input: string): string {
  return input.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function generateCardHtml(toolName: string, result: ToolCallResult<unknown>): string {
  const summary = esc(result.rawText || "");
  const data = esc(JSON.stringify(result.data ?? {}, null, 2));
  const ok = result.success ? "SUCCESS" : "FAILED";
  return `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <style>
      body { margin: 0; font-family: Inter, Arial, sans-serif; background: #0b1220; color: #e5e7eb; }
      .card { margin: 16px; border: 1px solid #334155; border-radius: 12px; background: #111827; padding: 16px; }
      .title { font-size: 18px; font-weight: 700; margin-bottom: 8px; }
      .meta { font-size: 12px; color: #93c5fd; margin-bottom: 12px; }
      .status { display: inline-block; border-radius: 999px; padding: 3px 10px; font-size: 11px; font-weight: 700; background: ${result.success ? "#064e3b" : "#7f1d1d"}; color: #fff; }
      .summary { margin-top: 12px; font-size: 13px; line-height: 1.5; }
      pre { margin-top: 12px; border: 1px solid #1f2937; background: #0f172a; border-radius: 8px; padding: 10px; font-size: 11px; overflow: hidden; white-space: pre-wrap; }
    </style>
  </head>
  <body>
    <div class="card">
      <div class="title">${esc(toolName)}</div>
      <div class="meta">Generated by GRASS agent</div>
      <span class="status">${ok}</span>
      <div class="summary">${summary}</div>
      <pre>${data}</pre>
    </div>
  </body>
</html>`;
}

export async function renderResultCard(toolName: string, result: ToolCallResult<unknown>): Promise<Buffer> {
  const html = generateCardHtml(toolName, result);
  const b = await getBrowser();
  const page = await b.newPage();
  try {
    await page.setViewport({ width: 900, height: 600 });
    await page.setContent(html, { waitUntil: "load" });
    const screenshot = await page.screenshot({ type: "jpeg", quality: 90 });
    return Buffer.from(screenshot);
  } finally {
    await page.close();
  }
}

